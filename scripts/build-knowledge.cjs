// Edit knowledge-content.json, then run: node scripts/build-knowledge.cjs
(function build(){
const fs=require('node:fs'),path=require('node:path'),root=path.resolve(__dirname,'..');
const {refs,articles:allArticles}=JSON.parse(fs.readFileSync(path.join(root,'knowledge-content.json'),'utf8'));
const slugs=new Set();
for(const a of allArticles){
  if(!/^[a-z0-9-]+$/.test(a.slug)||slugs.has(a.slug))throw Error('Invalid or duplicate article slug: '+a.slug);
  slugs.add(a.slug);
  for(const key of ['title','kind','category','basis','principle','body','question','answer'])if(typeof a[key]!=='string'||!a[key].trim())throw Error('Missing '+key+' in '+a.slug);
  if(!Array.isArray(a.sources)||!a.sources.length||a.sources.some(key=>!refs[key]))throw Error('Invalid sources in '+a.slug);
  if(!Array.isArray(a.related))throw Error('Missing related articles in '+a.slug);
}
for(const a of allArticles)for(const related of a.related)if(!slugs.has(related))throw Error('Missing related article: '+related);
const articles=allArticles.filter(a=>!a.archived),activeSlugs=new Set(articles.map(a=>a.slug));
for(const a of allArticles){
  if(/href=["'][^"']*(?:knowledge\.html|kb-[a-z0-9-]+\.html)/i.test(a.body))throw Error('Retired standalone link in '+a.slug+'; use #note-slug');
  for(const [,slug] of a.body.matchAll(/href=["']#note-([a-z0-9-]+)["']/g)){
    if(!slugs.has(slug)||(!a.archived&&!activeSlugs.has(slug)))throw Error('Unavailable note link in '+a.slug+': '+slug);
  }
}
const esc=v=>String(v).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const write=(name,data)=>fs.writeFileSync(path.join(root,name),data+'\n');

// Notes are published only in KhanOS. Archived material stays in the source file.
write('khanos-content.js','// Generated by scripts/build-knowledge.cjs.\nwindow.KHAN_NOTES = '+JSON.stringify(articles.map(a=>({...a,related:a.related.filter(slug=>activeSlugs.has(slug)),references:a.sources.map(key=>({title:refs[key][0],url:refs[key][1]}))}))).replace(/</g,'\\u003c')+';');

// Retained investigation pages use this search index to open notes in the desktop.
write('knowledge-index.js','// Generated by scripts/build-knowledge.cjs.\nwindow.knowledgePages = '+JSON.stringify(articles.map(a=>({name:a.title,url:'index.html#note-'+a.slug,type:a.kind||'Concept',keywords:a.category+' '+a.basis+' '+a.principle+' '+(a.keywords||''),slug:a.slug,category:a.category,question:a.question,answer:a.answer})),null,2)+';');

// The no-JavaScript fallback provides summaries, without links to retired pages.
const homePath=path.join(root,'index.html');
let homepage=fs.readFileSync(homePath,'utf8');
if(!homepage.includes('<!-- KHANOS STUDIES START -->')||!homepage.includes('<!-- KHANOS STUDIES END -->'))throw Error('KhanOS study markers are missing');
const fallback=articles.map(a=>`<article class="fallback-note"><strong>${esc(a.title)}</strong><span>${esc(a.principle)}</span></article>`).join('\n');
homepage=homepage.replace(/<!-- KHANOS STUDIES START -->[\s\S]*?<!-- KHANOS STUDIES END -->/,'<!-- KHANOS STUDIES START -->\n'+fallback+'\n<!-- KHANOS STUDIES END -->');
write('index.html',homepage.trimEnd());
console.log('Built '+articles.length+' active KhanOS notes, desktop search links, and homepage summaries. No standalone study pages are generated.');
})();
